def normalize_unicode_scripts_in_latex(
    latex_text: str,
) -> str:
    """
    Replace Unicode superscript and subscript glyphs with ordinary
    characters inside LaTeX script commands.

    This avoids missing-glyph squares when Arial does not contain a specific
    Unicode superscript or subscript character.

    Examples:
        10⁻³  ->  10\\textsuperscript{-3}
        g₂    ->  g\\textsubscript{2}

    Pandoc-generated constructs such as:

        \\textsuperscript{−3}

    are also normalized to use an ordinary ASCII minus.
    """

    # Clean scripts already generated by Pandoc from Word formatting.
    existing_script_re = re.compile(
        r"\\text(?P<kind>superscript|subscript)"
        r"\{(?P<content>[^{}]*)\}"
    )

    def clean_existing_script(
        match: re.Match[str],
    ) -> str:
        kind = match.group("kind")
        content = match.group("content")

        # Word commonly uses the mathematical Unicode minus U+2212.
        content = content.replace("−", "-")

        if kind == "superscript":
            content = content.translate(
                SUPERSCRIPT_TRANSLATION
            )
        else:
            content = content.translate(
                SUBSCRIPT_TRANSLATION
            )

        return (
            f"\\text{kind}"
            f"{{{content}}}"
        )

    latex_text = existing_script_re.sub(
        clean_existing_script,
        latex_text,
    )

    # Convert literal Unicode superscript sequences such as ⁻³.
    superscript_re = re.compile(
        f"[{re.escape(SUPERSCRIPT_CHARACTERS)}]+"
    )

    latex_text = superscript_re.sub(
        lambda match: (
            "\\textsuperscript{"
            + match.group(0).translate(
                SUPERSCRIPT_TRANSLATION
            )
            + "}"
        ),
        latex_text,
    )

    # Convert literal Unicode subscript sequences such as ₂.
    subscript_re = re.compile(
        f"[{re.escape(SUBSCRIPT_CHARACTERS)}]+"
    )

    latex_text = subscript_re.sub(
        lambda match: (
            "\\textsubscript{"
            + match.group(0).translate(
                SUBSCRIPT_TRANSLATION
            )
            + "}"
        ),
        latex_text,
    )

    return latex_text

def is_figure_legend_start(
    text: str | None,
) -> bool:
    """
    Recognize the first paragraph of a figure legend, including captions
    stored as ordinary Word paragraphs rather than Word headings.
    """
    if text is None:
        return False

    return (
        FIGURE_LEGEND_START_RE.match(
            norm(text)
        )
        is not None
    )


def section_disables_paragraph_spacing(
    heading_text: str,
) -> bool:
    """
    Disable paragraph spacing in References and in ordinary,
    supplementary, supplemental, and extended-data figure sections.

    This also recognizes individual headings such as:
        Figure 1
        Figure S1
        Supplementary Figure S1
        Supplemental Figure S1
        Extended Data Figure 1
    """
    normalized = (
        norm(heading_text)
        .casefold()
        .rstrip(":")
        .strip()
    )

    if normalized in NO_PARAGRAPH_SPACING_SECTION_TITLES:
        return True

    return normalized.startswith(
        NO_PARAGRAPH_SPACING_SECTION_PREFIXES
    )


def header_level_and_text(
    block: dict[str, Any],
) -> tuple[int, str] | None:
    """
    Return the level and normalized text of a Pandoc Header block.
    """
    if block.get("t") != "Header":
        return None

    content = block.get("c")

    if (
        not isinstance(content, list)
        or len(content) < 3
        or not isinstance(content[0], int)
        or not isinstance(content[2], list)
    ):
        return None

    level = content[0]
    text = norm(inline_text(content[2]))

    return level, text


def uses_selective_paragraph_spacing(
    heading_text: str,
) -> bool:
    """
    Return True for manuscript sections that require 12 pt paragraph
    spacing.
    """
    normalized = norm(heading_text).casefold().rstrip(":")

    return normalized in PARAGRAPH_SPACING_SECTION_TITLES

