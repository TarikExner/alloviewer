def qn(name: str) -> str:
    return f"{{{W_NS}}}{name}"


def norm(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def require_program(name: str) -> str:
    path = shutil.which(name)
    if not path:
        raise RuntimeError(f"Required executable not found on PATH: {name}")
    return path


def run(command: list[str], cwd: Path | None = None, capture: bool = False) -> str:
    result = subprocess.run(
        command,
        cwd=cwd,
        check=True,
        text=True,
        encoding="utf-8",
        stdout=subprocess.PIPE if capture else None,
    )
    return result.stdout if capture else ""


def paragraph_text(paragraph: etree._Element) -> str:
    return "".join(paragraph.xpath(".//w:t/text()", namespaces=NS))


def has_nontext_content(paragraph: etree._Element) -> bool:
    """Return True for content that must not be replaced as a blank line."""
    if paragraph.xpath(
        ".//w:drawing | .//w:pict | .//w:object | .//w:sym | "
        ".//w:fldSimple | .//w:instrText",
        namespaces=NS,
    ):
        return True

    # A page or column break is structural. An ordinary line break inside an
    # otherwise empty paragraph still represents visible vertical space.
    return bool(
        paragraph.xpath(
            ".//w:br[@w:type='page' or @w:type='column']",
            namespaces=NS,
        )
    )


def rewrite_paragraph(paragraph: etree._Element, text: str) -> None:
    """Replace paragraph content with one Normal-style text run."""
    p_pr = paragraph.find(qn("pPr"))
    if p_pr is None:
        p_pr = etree.Element(qn("pPr"))
        paragraph.insert(0, p_pr)

    for child in list(paragraph):
        if child is not p_pr:
            paragraph.remove(child)

    p_style = p_pr.find(qn("pStyle"))
    if p_style is None:
        p_style = etree.Element(qn("pStyle"))
        p_pr.insert(0, p_style)
    p_style.set(qn("val"), "Normal")

    run_node = etree.SubElement(paragraph, qn("r"))
    text_node = etree.SubElement(run_node, qn("t"))
    text_node.text = text


def marker_paragraph(text: str) -> etree._Element:
    paragraph = etree.Element(qn("p"))
    rewrite_paragraph(paragraph, text)
    return paragraph


def strip_direct_highlight(paragraph: etree._Element) -> None:
    nodes = paragraph.xpath(
        "./w:pPr/w:shd | .//w:rPr/w:highlight | .//w:rPr/w:shd",
        namespaces=NS,
    )
    for node in nodes:
        parent = node.getparent()
        if parent is not None:
            parent.remove(node)


def paragraph_style_ids(paragraph: etree._Element) -> set[str]:
    values = paragraph.xpath(
        "./w:pPr/w:pStyle/@w:val | .//w:rPr/w:rStyle/@w:val",
        namespaces=NS,
    )
    return {str(value) for value in values}


def strip_style_highlights(styles_xml: bytes, style_ids: set[str]) -> bytes:
    if not styles_xml or not style_ids:
        return styles_xml

    root = etree.fromstring(styles_xml)
    for style in root.xpath(".//w:style", namespaces=NS):
        if style.get(qn("styleId")) not in style_ids:
            continue
        for node in style.xpath(".//w:rPr/w:highlight | .//w:rPr/w:shd", namespaces=NS):
            parent = node.getparent()
            if parent is not None:
                parent.remove(node)

    return etree.tostring(root, xml_declaration=True, encoding="UTF-8", standalone=True)


def preprocess_docx(source: Path, destination: Path) -> list[str]:
    """Normalize markers, retain blank paragraphs, and expose Word sections."""
    with zipfile.ZipFile(source, "r") as archive:
        entries = {item.filename: archive.read(item.filename) for item in archive.infolist()}

    try:
        root = etree.fromstring(entries["word/document.xml"])
    except KeyError as exc:
        raise ValueError("Input is not a valid DOCX file.") from exc

    body = root.find(f".//{qn('body')}")
    if body is None:
        raise ValueError("DOCX body not found.")

    title_style_ids: set[str] = set()
    native_sections: list[str] = []
    on_title_page = True

    for paragraph in list(body):
        if paragraph.tag != qn("p"):
            continue

        text = norm(paragraph_text(paragraph))
        sect_pr = paragraph.find(f"./{qn('pPr')}/{qn('sectPr')}")
        explicit_section = SECTION_RE.fullmatch(text) is not None

        if on_title_page:
            strip_direct_highlight(paragraph)
            title_style_ids.update(paragraph_style_ids(paragraph))

        if explicit_section:
            rewrite_paragraph(paragraph, "[[DOCX_SECTION:nextPage]]")
            text = "[[DOCX_SECTION:nextPage]]"
        else:
            figure_match = FIGURE_RE.fullmatch(text)
            if figure_match:
                pages = figure_match.group("pages")
                normalized = f"[[PDF_FIGURE: {figure_match.group('name').strip()}"
                if pages:
                    normalized += f"; pages={pages.strip()}"
                rewrite_paragraph(paragraph, normalized + "]]" )
            elif not text and sect_pr is None and not has_nontext_content(paragraph):
                rewrite_paragraph(paragraph, BLANK_MARKER)

        if sect_pr is not None:
            type_node = sect_pr.find(qn("type"))
            kind = type_node.get(qn("val"), "nextPage") if type_node is not None else "nextPage"
            kind = kind or "nextPage"
            next_node = paragraph.getnext()
            next_text = norm(paragraph_text(next_node)) if next_node is not None and next_node.tag == qn("p") else ""
            if not (SECTION_RE.fullmatch(next_text) or INTERNAL_SECTION_RE.fullmatch(next_text)):
                paragraph.addnext(marker_paragraph(f"[[DOCX_SECTION:{kind}]]"))
            native_sections.append(kind)

        if explicit_section or sect_pr is not None:
            on_title_page = False

    entries["word/document.xml"] = etree.tostring(
        root, xml_declaration=True, encoding="UTF-8", standalone=True
    )
    if "word/styles.xml" in entries:
        entries["word/styles.xml"] = strip_style_highlights(
            entries["word/styles.xml"], title_style_ids
        )

    with zipfile.ZipFile(destination, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in entries.items():
            archive.writestr(name, data)

    return native_sections


def normalize_figure_key(value: str) -> str:
    value = value.strip().strip('"').strip("'").replace("\\", "/")
    value = value.rsplit("/", 1)[-1]
    if value.lower().endswith(".pdf"):
        value = value[:-4]
    return value.casefold()


def index_figures(directory: Path) -> dict[str, Figure]:
    if not directory.is_dir():
        raise FileNotFoundError(f"Figure directory not found: {directory}")

    paths = sorted(
        (p.resolve() for p in directory.iterdir() if p.is_file() and p.suffix.lower() == ".pdf"),
        key=lambda p: p.name.casefold(),
    )
    if not paths:
        raise FileNotFoundError(f"No top-level PDF figures found in: {directory}")

    result: dict[str, Figure] = {}
    for number, path in enumerate(paths, 1):
        key = normalize_figure_key(path.name)
        if key in result:
            raise ValueError(f"Duplicate case-insensitive PDF stem: {path.stem}")
        result[key] = Figure(key, path, f"figure_{number:04d}.pdf", len(PdfReader(str(path)).pages))
    return result


def parse_pages(spec: str | None, page_count: int) -> tuple[int, ...]:
    if not spec or spec.strip().casefold() == "all":
        return tuple(range(1, page_count + 1))

    pages: list[int] = []
    for token in spec.split(","):
        token = token.strip()
        if not token:
            continue
        if "-" in token:
            start, end = (int(value.strip()) for value in token.split("-", 1))
            if start > end:
                raise ValueError(f"Invalid page range: {token}")
            pages.extend(range(start, end + 1))
        else:
            pages.append(int(token))

    pages = list(dict.fromkeys(pages))
    if not pages or any(page < 1 or page > page_count for page in pages):
        raise ValueError(f"Invalid page selection {spec!r} for a {page_count}-page PDF.")
    return tuple(pages)


def inline_text(inlines: list[dict[str, Any]]) -> str:
    parts: list[str] = []
    for inline in inlines:
        kind, content = inline.get("t"), inline.get("c")
        if kind == "Str":
            parts.append(str(content))
        elif kind in {"Space", "SoftBreak", "LineBreak"}:
            parts.append(" ")
        elif kind in {"Code", "Math", "RawInline"} and isinstance(content, list):
            parts.append(str(content[-1]))
        elif kind in {"Emph", "Strong", "Strikeout", "Superscript", "Subscript", "SmallCaps"}:
            parts.append(inline_text(content))
        elif kind in {"Quoted", "Link", "Image", "Span"} and isinstance(content, list):
            nested = content[1] if len(content) > 1 and isinstance(content[1], list) else []
            parts.append(inline_text(nested))
    return "".join(parts)


def block_inlines(block: dict[str, Any]) -> list[dict[str, Any]] | None:
    kind, content = block.get("t"), block.get("c")
    if kind in {"Para", "Plain"} and isinstance(content, list):
        return content
    if kind == "Header" and isinstance(content, list) and len(content) >= 3:
        return content[2] if isinstance(content[2], list) else None
    return None


def block_text(block: dict[str, Any]) -> str | None:
    inlines = block_inlines(block)
    return norm(inline_text(inlines)) if inlines is not None else None


def nested_block_lists(block: dict[str, Any]) -> list[list[dict[str, Any]]]:
    kind, content = block.get("t"), block.get("c")
    if kind == "Div":
        return [content[1]]
    if kind == "BlockQuote":
        return [content]
    if kind == "BulletList":
        return list(content)
    if kind == "OrderedList":
        return list(content[1])
    if kind == "DefinitionList":
        return [definition for _term, definitions in content for definition in definitions]
    return []


def collect_insertions(blocks: list[dict[str, Any]], figures: dict[str, Figure]) -> list[Insertion]:
    result: list[Insertion] = []
    for block in blocks:
        text = block_text(block)
        match = FIGURE_RE.fullmatch(text or "")
        if match:
            key = normalize_figure_key(match.group("name"))
            figure = figures.get(key)
            if figure is None:
                available = ", ".join(item.source.stem for item in figures.values())
                raise FileNotFoundError(f"Figure {match.group('name')!r} not found. Available: {available}")
            result.append(Insertion(text or "", figure, parse_pages(match.group("pages"), figure.page_count)))
            continue
        for nested in nested_block_lists(block):
            result.extend(collect_insertions(nested, figures))
    return result


def strip_ast_highlights(value: Any) -> None:
    """Remove Pandoc background/highlight attributes that survived DOCX parsing."""
    if isinstance(value, dict):
        strip_ast_highlights(value.get("c"))
    elif isinstance(value, list):
        if (
            len(value) == 3
            and isinstance(value[0], str)
            and isinstance(value[1], list)
            and isinstance(value[2], list)
            and all(isinstance(pair, list) and len(pair) == 2 for pair in value[2])
        ):
            value[2][:] = [
                pair for pair in value[2]
                if str(pair[0]).casefold() not in {"background-color", "background", "highlight"}
            ]
        for item in value:
            strip_ast_highlights(item)


def meta_text(meta_value: Any) -> str:
    if not isinstance(meta_value, dict):
        return ""
    kind, content = meta_value.get("t"), meta_value.get("c")
    if kind == "MetaString":
        return norm(str(content))
    if kind == "MetaInlines" and isinstance(content, list):
        return norm(inline_text(content))
    if kind == "MetaBlocks" and isinstance(content, list):
        return norm(" ".join(block_text(block) or "" for block in content))
    return ""


def extract_title(
    document: dict[str, Any],
) -> str:
    """
    Extract the Pandoc title and remove ordinary, non-breaking, and
    zero-width whitespace from its edges.
    """
    meta = document.setdefault("meta", {})

    title = meta_text(
        meta.pop("title", None)
    )

    meta.pop("author", None)
    meta.pop("date", None)

    title = re.sub(
        r"^[\s\u00A0\u2007\u202F\u200B\uFEFF]+",
        "",
        title,
    )
    title = re.sub(
        r"[\s\u00A0\u2007\u202F\u200B\uFEFF]+$",
        "",
        title,
    )

    return title


def latex_escape(text: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in text)


def figure_latex(
    figure: Figure,
    page: int,
    scale: float,
) -> str:
    """
    Insert a large figure while retaining the normal footer height.

    The fancyhdr footer width is recalculated after each geometry change so
    the page number remains horizontally centered.
    """
    return (
        "\\par\n"
        "\\nolinenumbers\n"
        "\\newgeometry{"
        f"top={FIGURE_TOP_MARGIN_MM:.3f}mm,"
        f"bottom={FIGURE_BOTTOM_MARGIN_MM:.3f}mm,"
        f"left={FIGURE_SIDE_MARGIN_MM:.3f}mm,"
        f"right={FIGURE_SIDE_MARGIN_MM:.3f}mm,"
        f"footskip={FIGURE_FOOTSKIP_MM:.3f}mm"
        "}\n"
        "\\setlength{\\headwidth}{\\textwidth}\n"
        "\\thispagestyle{plain}\n"
        "\\null\\vfill\n"
        "\\noindent\\makebox[\\textwidth][c]{%\n"
        f"  \\includegraphics["
        f"page={page},"
        f"scale={scale:.8f}"
        f"]{{{figure.safe_name}}}%\n"
        "}\n"
        "\\vfill\\null\n"
        "\\restoregeometry\n"
        "\\setlength{\\headwidth}{\\textwidth}\n"
        "\\linenumbers"
    )


def section_latex(kind: str) -> str:
    kind = kind.casefold()
    if kind == "continuous":
        return r"\par"
    if kind == "oddpage":
        page_logic = r"\ifodd\value{page}\else\null\thispagestyle{empty}\newpage\fi"
    elif kind == "evenpage":
        page_logic = r"\ifodd\value{page}\null\thispagestyle{empty}\newpage\fi"
    else:
        page_logic = ""
    return "\\par\n\\nolinenumbers\n\\clearpage\n" + page_logic + "\n\\linenumbers"


def raw_block(latex: str) -> dict[str, Any]:
    return {"t": "RawBlock", "c": ["latex", latex]}


def transform_blocks(
    blocks: list[dict[str, Any]],
    insertion_map: dict[str, Insertion],
    scale: float,
    paragraph_spacing_scope: str,
) -> list[dict[str, Any]]:
    """
    Replace internal markers and switch paragraph spacing at level-1
    manuscript headings.

    paragraph_spacing_scope:
        selective:
            12 pt only in References and Figure Legends sections.
        all:
            12 pt throughout the document.
        none:
            No additional paragraph spacing.
    """
    if paragraph_spacing_scope not in {
        "selective",
        "all",
        "none",
    }:
        raise ValueError(
            "paragraph_spacing_scope must be "
            "'selective', 'all', or 'none'."
        )

    output: list[dict[str, Any]] = []
    skip_blanks = False

    for block in blocks:
        text = block_text(block)

        section_match = INTERNAL_SECTION_RE.fullmatch(
            text or ""
        )
        is_blank = BLANK_RE.fullmatch(
            text or ""
        ) is not None

        if section_match:
            while (
                output
                and output[-1].get("c")
                == ["latex", r"\ManuscriptBlankLine"]
            ):
                output.pop()

            output.append(
                raw_block(
                    section_latex(
                        section_match.group("kind")
                    )
                )
            )
            skip_blanks = True
            continue

        if is_blank:
            if not skip_blanks:
                output.append(
                    raw_block(r"\ManuscriptBlankLine")
                )
            continue

        skip_blanks = False

        figure_match = FIGURE_RE.fullmatch(text or "")

        if figure_match:
            insertion = insertion_map[norm(text or "")]

            for page in insertion.pages:
                output.append(
                    raw_block(
                        figure_latex(
                            insertion.figure,
                            page,
                            scale,
                        )
                    )
                )

            continue

        # Supplementary and extended-data figure captions in the DOCX are
        # Normal paragraphs rather than Pandoc Header blocks. Switch off
        # paragraph spacing when their first paragraph is encountered.
        if (
            paragraph_spacing_scope == "selective"
            and is_figure_legend_start(text)
        ):
            output.append(
                raw_block(
                    r"\ManuscriptParagraphSpacingOff"
                )
            )

        kind = block.get("t")
        content = block.get("c")

        if kind == "Div":
            content[1] = transform_blocks(
                content[1],
                insertion_map,
                scale,
                paragraph_spacing_scope,
            )

        elif kind == "BlockQuote":
            block["c"] = transform_blocks(
                content,
                insertion_map,
                scale,
                paragraph_spacing_scope,
            )

        elif kind == "BulletList":
            block["c"] = [
                transform_blocks(
                    item,
                    insertion_map,
                    scale,
                    paragraph_spacing_scope,
                )
                for item in content
            ]

        elif kind == "OrderedList":
            content[1] = [
                transform_blocks(
                    item,
                    insertion_map,
                    scale,
                    paragraph_spacing_scope,
                )
                for item in content[1]
            ]

        elif kind == "DefinitionList":
            for entry in content:
                entry[1] = [
                    transform_blocks(
                        item,
                        insertion_map,
                        scale,
                        paragraph_spacing_scope,
                    )
                    for item in entry[1]
                ]

        output.append(block)

        # Only level-1 headings switch the active manuscript section.
        # Subheadings within References or Figure Legends do not disable
        # paragraph spacing.
        header = header_level_and_text(block)

        if (
            paragraph_spacing_scope == "selective"
            and header is not None
        ):
            heading_level, heading_text = header

            if section_disables_paragraph_spacing(
                heading_text
            ):
                output.append(
                    raw_block(
                        r"\ManuscriptParagraphSpacingOff"
                    )
                )

            elif heading_level == 1:
                output.append(
                    raw_block(
                        r"\ManuscriptParagraphSpacingOn"
                    )
                )

    return output


def page_size(reader: PdfReader, page_number: int) -> tuple[float, float]:
    page = reader.pages[page_number - 1]
    width, height = float(page.cropbox.width), float(page.cropbox.height)
    if int(page.get("/Rotate", 0) or 0) % 360 in {90, 270}:
        width, height = height, width
    return width, height


def common_scale(
    insertions: list[Insertion],
    paper: str,
    margin_mm: float,
    max_scale: float,
    safety: float,
) -> float:
    """
    Calculate one common scale for all inserted figure pages.

    Figures use narrow top and side margins, but retain the normal manuscript
    bottom margin so the page number stays in its original position.
    """
    paper_width, paper_height = PAPER_SIZES_PT[paper]

    side_margin_pt = FIGURE_SIDE_MARGIN_MM * PT_PER_MM
    top_margin_pt = FIGURE_TOP_MARGIN_MM * PT_PER_MM
    bottom_margin_pt = FIGURE_BOTTOM_MARGIN_MM * PT_PER_MM

    usable_width = paper_width - 2.0 * side_margin_pt
    usable_height = (
        paper_height
        - top_margin_pt
        - bottom_margin_pt
    )

    if usable_width <= 0 or usable_height <= 0:
        raise ValueError(
            "The figure margins leave no usable page area."
        )

    readers: dict[Path, PdfReader] = {}
    limits: list[float] = []

    for insertion in insertions:
        reader = readers.setdefault(
            insertion.figure.source,
            PdfReader(str(insertion.figure.source)),
        )

        for page_number in insertion.pages:
            width, height = page_size(
                reader,
                page_number,
            )

            limits.append(
                min(
                    usable_width / width,
                    usable_height / height,
                )
            )

    if not limits:
        raise ValueError("No figure pages selected.")

    return min(
        max_scale,
        min(limits) * safety,
    )


