def convert_docx(pandoc: str, source: Path, media_dir: Path) -> dict[str, Any]:
    return json.loads(
        run(
            [pandoc, str(source), "--from=docx", "--to=json", f"--extract-media={media_dir}"],
            capture=True,
        )
    )


def assert_no_markers(text: str) -> None:
    for marker in ("[[SECTION_BREAK]]", "[[DOCX_SECTION:", "[[DOCX_BLANK]]", "[[PDF_FIGURE:"):
        if marker.casefold() in text.casefold():
            raise RuntimeError(f"Unresolved marker remained in generated LaTeX: {marker}")


def normalized_font_key(name: str) -> str:
    name = re.sub(r"^[A-Z]{6}\+", "", name).casefold()
    return re.sub(r"[^a-z0-9]+", "", name)


def validate_pdf_output(pdf_path: Path, font: str, body_size: float) -> None:
    """Reject stale or incorrectly formatted output instead of silently copying it."""
    reader = PdfReader(str(pdf_path))
    all_text = "\n".join(page.extract_text() or "" for page in reader.pages)
    assert_no_markers(all_text)

    page_index = next(
        (i for i, page in enumerate(reader.pages) if len(norm(page.extract_text() or "")) >= 200),
        None,
    )
    if page_index is None:
        raise RuntimeError("Could not find a substantial text page for PDF validation.")

    page = reader.pages[page_index]
    resources = page.get("/Resources")
    fonts = resources.get_object().get("/Font") if resources is not None else None
    font_names: list[str] = []
    if fonts is not None:
        for reference in fonts.get_object().values():
            font_dict = reference.get_object()
            base_font = font_dict.get("/BaseFont")
            if base_font is not None:
                font_names.append(str(base_font).lstrip("/"))
            descendants = font_dict.get("/DescendantFonts")
            if descendants is not None:
                for descendant in descendants:
                    descendant_name = descendant.get_object().get("/BaseFont")
                    if descendant_name is not None:
                        font_names.append(str(descendant_name).lstrip("/"))

    requested = normalized_font_key(font)
    if not any(requested in normalized_font_key(name) for name in font_names):
        raise RuntimeError(
            f"Generated PDF does not use {font!r} on text page {page_index + 1}. "
            f"Detected fonts: {sorted(set(font_names))}"
        )

    sizes: list[float] = []
    contents = page.get_contents()
    if contents is not None:
        for operands, operator in ContentStream(contents, reader).operations:
            if operator == b"Tf" and len(operands) >= 2:
                try:
                    sizes.append(float(operands[1]))
                except (TypeError, ValueError):
                    pass

    def has_size(target: float) -> bool:
        return any(abs(value - target) <= 0.3 for value in sizes)

    if not has_size(body_size):
        raise RuntimeError(
            f"Generated PDF does not contain {body_size:g} pt body text on "
            f"page {page_index + 1}. Detected sizes: "
            f"{sorted(set(round(value, 3) for value in sizes))}"
        )
    if not has_size(8.0):
        raise RuntimeError(
            "Generated PDF does not contain the expected 8 pt line numbers. "
            f"Detected sizes: {sorted(set(round(value, 3) for value in sizes))}"
        )


def save_debug(temp_dir: Path, debug_dir: Path, enabled: bool) -> None:
    if not enabled:
        return
    try:
        if debug_dir.exists():
            shutil.rmtree(debug_dir)
        shutil.copytree(temp_dir, debug_dir)
    except Exception as exc:
        print(f"Warning: could not save intermediate files: {exc}", file=sys.stderr)


def build(args: argparse.Namespace) -> None:
    source = args.source.resolve()
    output = args.output.resolve()
    figures_dir = args.figures_dir.resolve() if args.figures_dir else source.parent / "figures"

    if not source.is_file() or source.suffix.lower() != ".docx":
        raise FileNotFoundError(f"DOCX source not found: {source}")
    if output.suffix.lower() != ".pdf":
        raise ValueError("Output must use the .pdf extension.")
    if args.margin_mm <= 0 or args.font_size_pt <= 0 or args.line_spacing <= 0:
        raise ValueError("Margins, font size, and line spacing must be positive.")
    if args.line_number_step < 1 or args.first_page_number < 1:
        raise ValueError("Line-number step and first page number must be at least 1.")
    if not 0 < args.fit_safety <= 1 or args.max_scale <= 0:
        raise ValueError("Invalid figure scale settings.")

    pandoc = require_program(args.pandoc)
    xelatex = require_program(args.pdf_engine)
    figures = index_figures(figures_dir)
    output.parent.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="docx_pdf_") as temp_name:
        temp_dir = Path(temp_name)
        prepared = temp_dir / "prepared.docx"
        media_dir = temp_dir / "media"
        ast_path = temp_dir / "document.json"
        header_path = temp_dir / "header.tex"
        tex_path = temp_dir / "manuscript.tex"
        debug_dir = output.parent / f"{output.stem}_build_files"

        try:
            native_sections = preprocess_docx(source, prepared)
            document = convert_docx(pandoc, prepared, media_dir)
            strip_ast_highlights(document)
            title = extract_title(document)

            blocks = document.get("blocks")
            if not isinstance(blocks, list):
                raise ValueError("Pandoc returned invalid document blocks.")

            prepared_texts = [block_text(block) or "" for block in blocks]
            section_count = sum(
                INTERNAL_SECTION_RE.fullmatch(text) is not None
                for text in prepared_texts
            )
            blank_count = sum(
                BLANK_RE.fullmatch(text) is not None
                for text in prepared_texts
            )

            insertions = collect_insertions(blocks, figures)
            if not insertions:
                raise ValueError("No [[PDF_FIGURE: ...]] markers found.")

            scale = common_scale(
                insertions, args.paper, args.margin_mm, args.max_scale, args.fit_safety
            )
            insertion_map = {norm(item.raw_marker): item for item in insertions}
            processed = transform_blocks(
                blocks,
                insertion_map,
                scale,
                args.paragraph_spacing_scope,
            )

            prefix = [raw_block(r"\linenumbers")]
            if title:
                prefix.append(raw_block(r"\ManuscriptTitle{" + latex_escape(title) + "}"))
            document["blocks"] = prefix + processed

            copied: set[Path] = set()
            for insertion in insertions:
                if insertion.figure.source not in copied:
                    shutil.copy2(insertion.figure.source, temp_dir / insertion.figure.safe_name)
                    copied.add(insertion.figure.source)

            ast_path.write_text(json.dumps(document, ensure_ascii=False), encoding="utf-8")
            header_path.write_text(latex_header(args), encoding="utf-8")

            resources = os.pathsep.join([str(temp_dir), str(media_dir), str(source.parent)])
            run(
                [
                    pandoc,
                    str(ast_path),
                    "--from=json",
                    "--to=latex",
                    "--standalone",
                    "--pdf-engine=xelatex",
                    "--variable", "documentclass=article",
                    "--variable", f"classoption={args.font_size_pt:g}pt",
                    "--variable", f"fontsize={args.font_size_pt:g}pt",
                    "--variable", f"mainfont={args.main_font}",
                    "--include-in-header", str(header_path),
                    "--resource-path", resources,
                    "--output", str(tex_path),
                ],
                cwd=temp_dir,
            )

            latex_text = tex_path.read_text(
                encoding="utf-8",
            )

            latex_text = normalize_unicode_scripts_in_latex(
                latex_text
            )

            tex_path.write_text(
                latex_text,
                encoding="utf-8",
            )

            assert_no_markers(latex_text)

            command = [
                xelatex,
                "-interaction=nonstopmode",
                "-halt-on-error",
                "-file-line-error",
                tex_path.name,
            ]
            run(command, cwd=temp_dir)
            run(command, cwd=temp_dir)

            built_pdf = tex_path.with_suffix(".pdf")
            if not built_pdf.is_file():
                raise RuntimeError("XeLaTeX did not produce a PDF.")

            validate_pdf_output(
                built_pdf,
                font=args.main_font,
                body_size=args.font_size_pt,
            )
            shutil.copy2(built_pdf, output)

            print(f"Script version: {SCRIPT_VERSION}")
            print(f"Source DOCX: {source}")
            print(f"Figure directory: {figures_dir}")
            print(f"Indexed PDF figures: {len(figures)}")
            print(f"Figure markers found: {len(insertions)}")
            print(f"Native Word section breaks found: {len(native_sections)}")
            print(f"Total section markers prepared: {section_count}")
            print(f"Blank paragraphs prepared: {blank_count}")
            print(f"Common figure scale: {scale:.6f}")
            print(f"Formatting: {args.main_font}, {args.font_size_pt:g} pt, {args.line_spacing:g}-line spacing")
            print(f"Output PDF: {output}")
        finally:
            save_debug(temp_dir, debug_dir, args.keep_intermediate)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Convert DOCX to PDF, preserve section/blank markers, and insert vector PDF figures."
    )
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--figures-dir", type=Path)
    parser.add_argument("--paper", choices=sorted(PAPER_SIZES_PT), default="a4")
    parser.add_argument("--margin-mm", type=float, default=25.4)
    parser.add_argument("--main-font", default="Arial")
    parser.add_argument("--font-size-pt", type=float, default=11.0)
    parser.add_argument("--line-spacing", type=float, default=1.5)
    parser.add_argument("--line-number-step", type=int, default=1)
    parser.add_argument("--max-scale", type=float, default=0.95)
    parser.add_argument("--fit-safety", type=float, default=0.985)
    parser.add_argument("--first-page-number", type=int, default=1)
    parser.add_argument("--pdf-engine", default="xelatex")
    parser.add_argument("--pandoc", default="pandoc")
    parser.add_argument("--keep-intermediate", action="store_true")
    parser.add_argument(
        "--paragraph-spacing-scope",
        choices=("selective", "all", "none"),
        default="selective",
        help=(
            "Where to apply 12 pt spacing after paragraphs. "
            "'selective' applies it only in References and "
            "Figure Legends sections; 'all' applies it throughout "
            "the document; 'none' disables it. "
            "Default: selective."
        ),
    )
    return parser.parse_args()


def main() -> int:
    try:
        build(parse_args())
    except subprocess.CalledProcessError as exc:
        print(f"Build command failed with exit code {exc.returncode}.", file=sys.stderr)
        return exc.returncode or 1
    except Exception as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

